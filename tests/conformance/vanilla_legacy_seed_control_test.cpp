// Must match tools/analysis/density-probe.sh and legacy-seed-probe.sh.
constexpr double kK = 0.35;
constexpr int kMinY = -64;
constexpr int kHeight = 384;

/// The noises legacy-seed-probe.sh ships in its `<spec>.noises.json` sidecar,
/// repeated here because a test that reads its own expectations out of the
/// fixture cannot fail when the fixture changes.
struct Noise {
    const char* id;
    int firstOctave;
    std::array<double, 3> amplitudes;
    std::size_t amplitudeCount;
};

constexpr Noise kNa{"stratum:na", -3, {1.0, 0.0, 0.0}, 1};
constexpr Noise kNmulti{"stratum:nmulti", -5, {1.0, 1.0, 1.0}, 3};
constexpr Noise kNskip{"stratum:nskip", -5, {1.0, 0.0, 1.0}, 3};
constexpr Noise kNb{"stratum:nb", -3, {1.0, 0.0, 0.0}, 1};

struct Dimension {
    const char* name;
    bool legacy;
    Noise noise;
    double scale;
    /// Only meaningful for a legacy dimension: the largest share of columns
    /// the modern rule may reach there before it stops looking like this
    /// dimension's null.
    ///
    /// THE DENOMINATORS MATCH, which they did not before. These ceilings are
    /// fractions of the ~2304 columns this file scores, so they are justified
    /// against what the modern rule ACTUALLY reaches over 2304 columns — the
    /// numbers below, measured here on both seeds — and not against the
    /// scan's null, which is reported per 128 subsampled columns and cannot
    /// be compared to a 2304-column count without first being turned into a
    /// rate.
    ///
    ///   scale 2      12-23 of 2304 (0.52-1.00%), ceiling 0.03 = 69/2304
    ///   scale 0.5    58-61 of 2304 (2.52-2.65%), ceiling 0.08 = 184/2304
    ///   scale 0.125  246-262 of 2304 (10.68-11.37%), ceiling 0.25 = 576/2304
    ///
    /// Each ceiling is 2.2 to 3.0 times the largest count measured at that
    /// scale — headroom for a different seed, not for a signal. As a rate the
    /// scan agrees: its null MEAN at seed 42 is 0.61-0.84% at scale 2, 2.55%
    /// at 0.5 and 10.15% at 0.125, which brackets the measured counts above.
    /// The null MAX (7-9/128, 18/128, 47/128 — 5.5%, 14%, 37%) is deliberately
    /// NOT the reference: it is the best of every wrong candidate scored, so
    /// sitting under it argues the wrong way. A ceiling has to be near the
    /// null's CENTRE to mean anything.
    double nullCeiling;
};

constexpr std::array<Dimension, 9> kDimensions{{
    {"leg_single", true, kNa, 2.0, 0.03},
    {"mod_single", false, kNa, 2.0, 0.0},
    {"leg_twin", true, kNb, 2.0, 0.03},
    {"leg_multi", true, kNmulti, 2.0, 0.03},
    {"mod_multi", false, kNmulti, 2.0, 0.0},
    {"leg_skip", true, kNskip, 2.0, 0.03},
    {"mod_skip", false, kNskip, 2.0, 0.0},
    {"leg_skip_q4", true, kNskip, 0.5, 0.08},
    {"leg_skip_q16", true, kNskip, 0.125, 0.25},
}};

/// The seeds legacy-seed-probe.sh was run at. Two, because one world seed
/// agreeing with an RNG-driven derivation is evidence that it agrees once.
constexpr std::array<std::int64_t, 2> kSeeds{42, 31337};

struct Column {
    double x = 0.0;
    double z = 0.0;
    double value = 0.0;
};

[[nodiscard]] double quantum(double scale) {
    return 2.0 / static_cast<double>(kHeight) / (kK * scale);
}

[[nodiscard]] std::filesystem::path probeRoot(std::int64_t seed) {
    return std::filesystem::path{STRATUM_FIXTURES_DIR} / "1.21.11" / "probes" /
           ("legseed_s" + std::to_string(seed));
}

/// Every cell-corner column of one probe region, inverted into a reading of
/// the noise at (x, 0, z). Columns with no block belong to chunks the server
/// left unbuilt around the forceloaded square; a column whose terrain reached
/// the floor or the ceiling ran past the gradient's range and its height no
/// longer carries the value. Both are dropped rather than counted, which would
/// let any candidate that also saturates agree for free.
[[nodiscard]] std::vector<Column> readColumns(const std::filesystem::path& region, double scale) {
    std::vector<Column> columns;
    const stratum::region::RegionFile file = stratum::region::RegionFile::open(region);
    for (std::int32_t chunkZ = 0; chunkZ < 32; ++chunkZ) {
        for (std::int32_t chunkX = 0; chunkX < 32; ++chunkX) {
            if (!file.hasChunk(chunkX, chunkZ)) {
                continue;
            }
            const stratum::chunk::Chunk decoded = stratum::chunk::Chunk::decode(
                stratum::nbt::read(file.readChunk(chunkX, chunkZ)).root);
            for (int localZ = 0; localZ < 16; ++localZ) {
                for (int localX = 0; localX < 16; ++localX) {
                    const std::int32_t x = (chunkX * 16) + localX;
                    const std::int32_t z = (chunkZ * 16) + localZ;
                    if ((x % 4) != 0 || (z % 4) != 0) {
                        continue;
                    }
                    int surface = kMinY - 1;
                    for (int y = kMinY + kHeight - 1; y >= kMinY; --y) {
                        const stratum::chunk::BlockState* block =
                            decoded.blockAt(localX, y, localZ);
                        if (block != nullptr && block->name != "minecraft:air") {
                            surface = y;
                            break;
                        }
                    }
                    if (surface <= kMinY || surface >= kMinY + kHeight - 1) {
                        continue;
                    }
                    const double gradient =
                        1.0 - (2.0 * ((surface + 0.5) - kMinY) / static_cast<double>(kHeight));
                    columns.push_back(
                        {static_cast<double>(x), static_cast<double>(z), -gradient / (kK * scale)});
                }
            }
        }
    }
    return columns;
}

/// A value put through the quantisation the server's terrain imposes, which is
/// the step `--plant` depends on: the server places a block wherever
/// K*scale*f + g(y) is positive, so the crossing sits at
/// min_y + height * (1 + K*scale*f) / 2 and the surface is the highest whole y
/// strictly below it.
[[nodiscard]] double quantise(double value, double scale) {
    const double crossing = (((1.0 + (value * kK * scale)) * kHeight / 2.0) + kMinY);
    const auto surface = static_cast<int>(std::ceil(crossing)) - 1;
    const double back = 1.0 - (2.0 * ((surface + 0.5) - kMinY) / static_cast<double>(kHeight));
    return -back / (kK * scale);
}

/// lib/src/noise_registry.cpp's modern derivation, spelled the way that file
/// spells it: one positional fork of the world seed, the noise's identifier
/// hashed into it, and NormalNoise on top.
/// Which of the three SHAPES the probe carries a dimension is an instance of.
/// `stratum:na` and `stratum:nb` differ only in their identifier, so they are
/// the same shape reached through two different seeds; the q4 and q16
/// dimensions are the skip shape read back at a coarser output scale.
enum class Shape : std::size_t { Single = 0, Multi = 1, Skip = 2 };
constexpr std::size_t kShapeCount = 3;
constexpr std::array<const char*, kShapeCount> kShapeNames{"1-octave", "3-octave", "skip"};

[[nodiscard]] Shape shapeOf(const Noise& noise) {
    if (noise.amplitudeCount == 1) {
        return Shape::Single;
    }
    // > 0.0 rather than != 0.0: the amplitudes are 0.0 or 1.0 and the project
    // builds with -Wfloat-equal.
    return noise.amplitudes[1] > 0.0 ? Shape::Multi : Shape::Skip;
}

/// One dimension's readback described without reference to any candidate
/// rule: how wide the values spread, and how strongly a column agrees with
/// its neighbour 4 blocks away. This is the measurement that bounds caveat 2
/// in the header — a legacy dimension whose pipeline differed from its modern
/// mirror in more than the seeding would not match its mirror here.
struct Profile {
    double sd = 0.0;
    double lag4 = 0.0;
    std::size_t lagPairs = 0;
};

/// Flat index into the lattice below, each operand widened before the
/// multiply rather than after it — the same spelling
/// tools/analysis/legacy-seed-analyze.cpp uses, and for the same reason.
[[nodiscard]] std::size_t latticeIndex(int gx, int gz, int side) {
    return (static_cast<std::size_t>(gz) * static_cast<std::size_t>(side)) +
           static_cast<std::size_t>(gx);
}

[[nodiscard]] Profile profileOf(const std::vector<Column>& columns) {
    Profile profile;
    if (columns.empty()) {
        return profile;
    }
    double sum = 0.0;
    for (const Column& column : columns) {
        sum += column.value;
    }
    const double mean = sum / static_cast<double>(columns.size());
    double variance = 0.0;
    for (const Column& column : columns) {
        const double d = column.value - mean;
        variance += d * d;
    }
    variance /= static_cast<double>(columns.size());
    profile.sd = std::sqrt(variance);

    // A dense lattice rather than a map: the probe reads every 4th block of a
    // 512-block region, so the grid is 128x128.
    constexpr int kStep = 4;
    constexpr int kSide = 512 / kStep;
    std::vector<double> grid(static_cast<std::size_t>(kSide) * kSide, 0.0);
    std::vector<char> present(static_cast<std::size_t>(kSide) * kSide, 0);
    for (const Column& column : columns) {
        const int gx = static_cast<int>(column.x) / kStep;
        const int gz = static_cast<int>(column.z) / kStep;
        if (gx < 0 || gx >= kSide || gz < 0 || gz >= kSide) {
            continue;
        }
        const std::size_t index = latticeIndex(gx, gz, kSide);
        grid[index] = column.value;
        present[index] = 1;
    }

    double covariance = 0.0;
    std::size_t pairs = 0;
    for (int gz = 0; gz < kSide; ++gz) {
        for (int gx = 0; gx < kSide; ++gx) {
            const std::size_t here = latticeIndex(gx, gz, kSide);
            if (present[here] == 0) {
                continue;
            }
            const double a = grid[here] - mean;
            if (gx + 1 < kSide) {
                const std::size_t east = latticeIndex(gx + 1, gz, kSide);
                if (present[east] != 0) {
                    covariance += a * (grid[east] - mean);
                    ++pairs;
                }
            }
            if (gz + 1 < kSide) {
                const std::size_t south = latticeIndex(gx, gz + 1, kSide);
                if (present[south] != 0) {
                    covariance += a * (grid[south] - mean);
                    ++pairs;
                }
            }
        }
    }
    profile.lagPairs = pairs;
    if (pairs != 0 && variance > 0.0) {
        profile.lag4 = covariance / (static_cast<double>(pairs) * variance);
    }
    return profile;
}

/// Running mean of one statistic over the instances of one shape on one side
/// of the mirror.
struct Tally {
    double total = 0.0;
    std::size_t count = 0;

    void add(double value) {
        total += value;
        ++count;
    }

    [[nodiscard]] double mean() const {
        return count == 0 ? 0.0 : total / static_cast<double>(count);
    }
};

[[nodiscard]] stratum::noise::NormalNoise modernNoise(const Noise& noise, std::int64_t worldSeed) {
    const stratum::rng::XoroshiroPositionalFactory factory{worldSeed};
    stratum::rng::Xoroshiro128PlusPlus random = factory.fromHashOf(noise.id);
    return stratum::noise::NormalNoise::create(
        random, noise.firstOctave,
        std::span<const double>{noise.amplitudes.data(), noise.amplitudeCount});
}

