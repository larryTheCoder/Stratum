//
// SPEC §11 records that candidate derivations of a NAMED noise's seed under
// `legacy_random_source` were scored against server output and that none
// survived — 270,000 of them when this file was written, and 729,535,800 over
// two worlds since the stack-shape, per-octave-salting, frequency and
// declaration-order axes were added. tools/analysis/legacy-seed-analyze.cpp is that scan, and it
// calibrates itself with `--plant`: a candidate planted inside the scanned
// space comes back rank 1, sole survivor, every column.
//
// THE PLANT CANNOT CLOSE THE ARGUMENT, and that is what this file is for. A
// plant synthesises its readings through the analyzer's OWN forward model, so
// a wrong model — a wrong persistence schedule, a wrong valueFactor, a missing
// second stack, a wrong cell-corner assumption, a wrong inversion of the
// gradient — is shared by the plant and the scan alike and the plant still
// returns rank 1. It shows the statistic is SENSITIVE. It does not show the
// model is RIGHT, and a refutation resting on it alone rests on nothing.
//
// SO SCORE A RULE THAT IS ALREADY KNOWN TO BE RIGHT. The probe worlds carry
// mirror dimensions — mod_single, mod_multi, mod_skip — that name the same
// noises without the legacy flag, generated by the same server start from the
// same seed. Their noises are therefore seeded by the modern derivation
// lib/src/noise_registry.cpp implements:
// XoroshiroPositionalFactory(worldSeed).fromHashOf(id), then
// NormalNoise::create. Put THAT through the identical readback, the identical
// band and the identical columns, and if it comes back whole then a correct
// named-noise rule is recoverable through this apparatus, and the legacy rule
// is absent from the searched space rather than invisible to the tool.
//
// Two things are asserted, and the second is the one that buys the plant's
// remaining ground:
//
//   * the modern rule recovers every column of every mirror dimension, and
//   * it does so EXACTLY through the same `quantise` inversion the plant
//     relies on — the model value put back through the block quantisation
//     lands on the server's own reading as a double, not near it.
//
// The second is not decoration. Breaking the inversion the way it was once
// actually broken — `floor(t - 0.5)` for `ceil(t) - 1`, which made the plant
// score 51% — leaves the FIRST assertion at every column and shows up only in
// the second, at about half of them. A band one terrain block wide cannot see
// it. The analyzer carries a third arm this file has no use for, comparing
// its own hand-rolled forward model and `valueFactor` against the library's
// bit for bit; here the library IS the model, so there is nothing to compare.
//
// And the mirror runs the other way too: the same rule on the legacy
// dimensions of the same world must sit at that dimension's measured null. A
// rule that won because of the readback rather than because of the seeding
// would score alike on both sides.
//
// THE NEGATIVE CONTROL closes that argument properly, and the legacy mirror
// alone does not. The legacy mirror varies the FLAG and the seeding together,
// so it cannot separate "the seeding is what is being recovered" from "the
// flag changes something else". Scoring the same modern derivation at
// worldSeed + 1 against the SAME mod_* dimensions varies one thing only. It
// must fall to the null; if it did not, the recovery above would be the
// readback accepting anything.
//
// TWO CAVEATS, and the second is the one this apparatus cannot discharge.
//
//   1. It does not widen the searched space. A control on a modern rule says
//      nothing about whether the legacy rule uses a stack shape the scan
//      never enumerates. That was "the likeliest place for it to hide" when
//      this was written; the stack shape, the per-octave salting, the
//      frequency and the declaration ordinal have since been enumerated and
//      came back empty, and the "the widened legacy-seed axes are axes" case
//      below is what says those axes are axes. (Cases are named rather than
//      numbered here: this file has grown two more since, and an ordinal that
//      silently comes to mean a different case is worse than no reference.)
//      The remaining gap is a SKIP whose step count is not a
//      multiple of 262 — and NOT, as this said until it was measured, the
//      shape `end_islands` uses: a Perlin block is 262 LCG steps and
//      262 x 66 = 17292, so that one is block offset 66 and inside the sweep.
//      The last case in this file is that measurement. See SPEC §11.
//
//   2. Everything validated here is validated on the MODERN dimensions. The
//      readback, the coordinate convention, the band and the `quantise`
//      inversion are shown correct where the legacy flag is absent, so the
//      step from "no survivor" to "absent from the space rather than
//      invisible to the tool" ASSUMES the flag changes the seeding and
//      nothing else in the terrain pipeline. Nothing here measures that
//      directly, and nothing short of the pipeline itself could.
//
//      What this file does instead is bound the assumption. If the flag also
//      moved the gradient, the output scale, the cell spacing or the sampling
//      coordinates, the legacy readback would not have the same SPREAD or the
//      same NEIGHBOUR-TO-NEIGHBOUR structure as its modern mirror. Both are
//      measured below, per noise shape, at lag 4 — the probe's own column
//      spacing, where a change in cell size or frequency bites hardest. It is
//      a refutable statement rather than a proof, and it is what replaced a
//      bare assumption. See SPEC §11.
//
// AND WHAT THE CONTROL DOES NOT REACH, inside the apparatus rather than
// outside it: `streamBlocks` under `Generator::Lcg` — Java `Random` driving
// `PerlinNoise::fromRandom`, which half of the scanned candidates use — is
// exercised by neither the control nor this file. Both run Xoroshiro128++
// only, because the modern derivation is the rule known to be right. That
// path is validated against the server in
// tests/conformance/vanilla_legacy_blended_test.cpp, where
// `BlendedNoise::legacyFromWorldSeed` is `JavaRandom{worldSeed}` handed
// straight into the same `PerlinNoise::fromRandom`.
//
// AND IT DOES NOT REACH THE ANALYZER'S CASCADE, which is the seam the plants
// and this control leave between them. The 8-column screen and the 128-column
// gate meet the SERVER's readings only through candidates that are all wrong,
// and meet a CORRECT candidate only through a plant's SYNTHETIC readings; the
// two have never been through the screen together, and the "the modern rule is
// outside the legacy-seed scan's space" case below says they never can,
// because the rule that IS right is not a member of the scanned space — its
// 128-bit Xoroshiro seed and Seed128 per-octave salt lie off the scan's 64-bit
// axes. What carries the real-data half is the `exact` assertion
// below — the model value put back through `quantise` landing on the server's
// own reading as a double, on every column of every mirror — so a correct
// candidate would clear an 8-column screen drawn from those readings by
// construction rather than by luck. See SPEC §11.
//
// THE NULL IS PER-DIMENSION. A column counts as agreement within half a
// quantum, a quantum being one block of terrain — 2 / height / (K * scale) —
// so the coarser copies of the same noise accept a wider band and ANY wrong
// rule scores higher there for no other reason. The ceilings below are
// per-dimension and come from the scan's own measured null (its `--scan` line
// prints mean and max for each), not from one number quoted across
// configurations. That mistake is how a 16% score once read as an outlier
// against 0-5% siblings when it was its own dimension's null; see SPEC §11.
//
// The fixtures come from tools/analysis/legacy-seed-probe.sh and are
// Mojang-derived, so they are never committed (SPEC §12). Without them this
// SKIPs — and a skip here is not a pass: Catch2 exits 4 when every selected
// case skips, and ctest reads that as a skip rather than as success only
// because catch_discover_tests sets SKIP_RETURN_CODE 4 (Catch.cmake:219).
// Run the binary by hand and the shell reports 4, not 0.
//
// It skips on BOTH seeds or on neither. Scoring one world and reporting a
// pass is the failure mode this file exists to refuse: one world seed
// agreeing with an RNG-driven derivation is evidence that it agrees once.
