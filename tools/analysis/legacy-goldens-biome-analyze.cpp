/// column instead of thirty-two.
constexpr std::int32_t kNetherSampleY = 64;

[[nodiscard]] std::filesystem::path findUnder(const std::filesystem::path& root,
                                              std::string_view filename,
                                              std::string_view grandparent) {
    if (!std::filesystem::is_directory(root)) {
        return {};
    }
    for (const auto& entry : std::filesystem::recursive_directory_iterator(root)) {
        if (entry.is_regular_file() && entry.path().filename() == filename &&
            entry.path().parent_path().parent_path().filename() == grandparent) {
            return entry.path();
        }
    }
    return {};
}

[[nodiscard]] std::filesystem::path findWorldgenTree(const std::filesystem::path& root) {
    if (!std::filesystem::is_directory(root)) {
        return {};
    }
    for (const auto& entry : std::filesystem::recursive_directory_iterator(root)) {
        if (entry.is_directory() && entry.path().filename() == "worldgen" &&
            std::filesystem::is_directory(entry.path() / "density_function")) {
            return entry.path();
        }
    }
    return {};
}

[[nodiscard]] std::filesystem::path regionOf(const std::filesystem::path& root, std::int64_t seed,
                                             std::string_view dimension) {
    if (!std::filesystem::is_directory(root)) {
        return {};
    }
    const std::string wanted = "seed-" + std::to_string(seed);
    for (const auto& entry : std::filesystem::recursive_directory_iterator(root)) {
        if (!entry.is_regular_file() || entry.path().filename() != "r.0.0.mca") {
            continue;
        }
        const std::filesystem::path parent = entry.path().parent_path();
        if (parent.filename() == dimension && parent.parent_path().filename() == wanted) {
            return entry.path();
        }
    }
    return {};
}

// --- the readback -----------------------------------------------------------

/// One 4x4x4 cell of a golden region: where it is, and which biome vanilla
/// stored there. `biome` indexes the parameter list's own entry order, so the
/// scoring loop compares two small integers instead of two strings.
struct Cell {
    std::int32_t x = 0;
    std::int32_t y = 0;
    std::int32_t z = 0;
    std::uint16_t biome = 0;
    /// True when at least one of the four cells 4 blocks away inside the same
    /// chunk carries a DIFFERENT stored biome. Those columns sit within one
    /// cell of a partition boundary, where an arbitrarily small error in the
    /// climate field flips the answer, so they are the ones a near-miss
    /// candidate gets wrong for free and a wrong one gets right for free.
    /// Counted so the denominator can be stated with and without them.
    bool boundary = false;
};

struct World {
    std::int64_t seed = 0;
    std::vector<Cell> cells;
    /// Cells whose stored biome is not the same all the way down the column.
    /// Must be zero; the Nether's `y_scale: 0.0` requires it.
    std::size_t varyingWithY = 0;
};

/// Maps a stored biome name onto the parameter list's entry order. A name the
/// table does not contain is an error rather than a bucket: the Nether's five
/// biomes are the whole table, and a sixth would mean the table being read is
/// not the one the world was generated from.
class BiomeIndex {
public:
    explicit BiomeIndex(const biome::ParameterList& table) {
        for (const auto& entry : table.entries()) {
            const std::string name = entry.biome.toString();
            if (!index_.contains(name)) {
                index_.emplace(name, names_.size());
                names_.push_back(name);
            }
        }
    }

    [[nodiscard]] std::optional<std::uint16_t> find(const std::string& name) const {
        const auto found = index_.find(name);
        if (found == index_.end()) {
            return std::nullopt;
        }
        return static_cast<std::uint16_t>(found->second);
    }

    [[nodiscard]] const std::string& nameOf(std::uint16_t at) const { return names_[at]; }

    [[nodiscard]] std::size_t size() const noexcept { return names_.size(); }

private:
    std::map<std::string, std::size_t> index_;
    std::vector<std::string> names_;
};

/// Reads one golden Nether region into cells. @p chunkStride subsamples
/// chunks; the cells inside a chunk are always all sixteen, so the
/// boundary test below always has its neighbours.
[[nodiscard]] World readNetherWorld(const std::filesystem::path& region, std::int64_t seed,
                                    const BiomeIndex& biomes, std::int32_t chunkStride) {
    World world;
    world.seed = seed;
    const region::RegionFile file = region::RegionFile::open(region);
    for (std::int32_t chunkZ = 0; chunkZ < region::kChunksPerAxis; chunkZ += chunkStride) {
        for (std::int32_t chunkX = 0; chunkX < region::kChunksPerAxis; chunkX += chunkStride) {
            if (!file.hasChunk(chunkX, chunkZ)) {
                continue;
            }
            const chunk::Chunk decoded =
                chunk::Chunk::decode(nbt::read(file.readChunk(chunkX, chunkZ)).root);

            std::array<std::optional<std::uint16_t>, 16> local{};
            for (int cellZ = 0; cellZ < 4; ++cellZ) {
                for (int cellX = 0; cellX < 4; ++cellX) {
                    const auto offset =
                        (static_cast<std::size_t>(cellZ) * 4U) + static_cast<std::size_t>(cellX);
                    const std::string* columnBiome = nullptr;
                    const std::string* atSampleY = nullptr;
                    for (const auto& section : decoded.sections()) {
                        if (section.biomes.empty()) {
                            continue;
                        }
                        for (int cellY = 0; cellY < 4; ++cellY) {
                            const std::size_t index =
                                (static_cast<std::size_t>(cellY) * 16U) + offset;
                            if (index >= section.biomes.size()) {
                                continue;
                            }
                            const std::string& here = section.biomePalette[section.biomes[index]];
                            if (columnBiome == nullptr) {
                                columnBiome = &here;
                            } else if (here != *columnBiome) {
                                ++world.varyingWithY;
                            }
                            if ((section.y * 16) + (cellY * 4) == kNetherSampleY) {
                                atSampleY = &here;
                            }
                        }
                    }
                    if (atSampleY == nullptr) {
                        continue;
                    }
                    const std::optional<std::uint16_t> found = biomes.find(*atSampleY);
                    if (!found.has_value()) {
                        std::fprintf(stderr,
                                     "golden nether region stores biome '%s', which the loaded "
                                     "parameter list does not contain\n",
                                     atSampleY->c_str());
                        std::exit(1);
                    }
                    local[offset] = found;
                }
            }

            for (int cellZ = 0; cellZ < 4; ++cellZ) {
                for (int cellX = 0; cellX < 4; ++cellX) {
                    const auto offset =
                        (static_cast<std::size_t>(cellZ) * 4U) + static_cast<std::size_t>(cellX);
                    if (!local[offset].has_value()) {
                        continue;
                    }
                    bool boundary = false;
                    constexpr std::array<std::array<int, 2>, 4> kNeighbours{
                        {{-1, 0}, {1, 0}, {0, -1}, {0, 1}}};
                    for (const auto& step : kNeighbours) {
                        const int nx = cellX + step[0];
                        const int nz = cellZ + step[1];
                        if (nx < 0 || nx > 3 || nz < 0 || nz > 3) {
                            continue;
                        }
                        const auto at =
                            (static_cast<std::size_t>(nz) * 4U) + static_cast<std::size_t>(nx);
                        if (local[at].has_value() && *local[at] != *local[offset]) {
                            boundary = true;
                        }
                    }
                    world.cells.push_back(Cell{.x = (chunkX * 16) + (cellX * 4),
                                               .y = kNetherSampleY,
                                               .z = (chunkZ * 16) + (cellZ * 4),
                                               .biome = *local[offset],
                                               .boundary = boundary});
                }
            }
        }
    }
    return world;
}

// --- the forward model ------------------------------------------------------
//
// A NormalNoise built from Perlin blocks this file draws itself, because
// noise::NormalNoise only builds from Xoroshiro128++ and half the candidate
// space drives a Java LCG. Compared against the library bit for bit by
// --model, for the three noises actually in play.

struct Layout {
    struct Octave {
        std::size_t block = 0;
        double amplitude = 0.0;
        double persistence = 0.0;
        double frequency = 0.0;
    };

    std::vector<Octave> first;
    std::vector<Octave> second;
    double valueFactor = 1.0;
    std::size_t blocksPerNoise = 0;
};

/// `amplitude != 0.0`, spelled so the project's -Wfloat-equal does not fire.
[[nodiscard]] bool nonZero(double amplitude) {
    return std::abs(amplitude) > 0.0;
}

[[nodiscard]] Layout layoutFor(const density::NoiseParameters& parameters) {
    Layout layout;
    const auto count = static_cast<int>(parameters.amplitudes.size());
    std::size_t block = 0;
    for (std::vector<Layout::Octave>* stack : {&layout.first, &layout.second}) {
        double frequency = std::ldexp(1.0, parameters.firstOctave);
        double persistence = std::ldexp(1.0, count - 1) / (std::ldexp(1.0, count) - 1.0);
        for (const double amplitude : parameters.amplitudes) {
            if (nonZero(amplitude)) {
                stack->push_back({block, amplitude, persistence, frequency});
                ++block;
            }
            frequency *= 2.0;
            persistence *= 0.5;
        }
    }
    layout.blocksPerNoise = block;

    std::size_t first = 0;
    std::size_t last = parameters.amplitudes.size();
    while (last > first && !nonZero(parameters.amplitudes[last - 1])) {
        --last;
    }
    while (first < last && !nonZero(parameters.amplitudes[first])) {
        ++first;
    }
    const auto effective = static_cast<double>(last - first);
    layout.valueFactor = (1.0 / 6.0) / (0.1 * (1.0 + (1.0 / effective)));
    return layout;
}

[[nodiscard]] double sampleStack(const std::vector<Layout::Octave>& stack,
                                 const std::vector<noise::PerlinNoise>& blocks, std::size_t offset,
                                 double x, double y, double z) {
    double total = 0.0;
    for (const Layout::Octave& octave : stack) {
        const noise::PerlinNoise& perlin = blocks[offset + octave.block];
        total += (perlin.sample(x * octave.frequency, y * octave.frequency, z * octave.frequency) *
                  octave.amplitude) *
                 octave.persistence;
    }
    return total;
}

[[nodiscard]] double sampleNormal(const Layout& layout,
                                  const std::vector<noise::PerlinNoise>& blocks, std::size_t offset,
                                  double x, double y, double z) {
    constexpr double kSecondFrequency = 337.0 / 331.0;
    const double combined = sampleStack(layout.first, blocks, offset, x, y, z) +
                            sampleStack(layout.second, blocks, offset, x * kSecondFrequency,
                                        y * kSecondFrequency, z * kSecondFrequency);
    return combined * layout.valueFactor;
}

/// The Perlin blocks the MODERN rule draws, in the order layoutFor indexes
/// them. lib/src/noise_registry.cpp's positional fork plus lib/src/perlin.cpp's
/// per-octave "octave_<n>" salt, spelled out rather than reached through
/// OctaveNoise, because the point of the `stack` arm is to drive THIS FILE'S
/// sampleNormal.
[[nodiscard]] std::vector<noise::PerlinNoise>
modernBlocksFor(const density::NoiseParameters& parameters, std::string_view id,
                std::int64_t worldSeed) {
    const rng::XoroshiroPositionalFactory factory{worldSeed};
    rng::Xoroshiro128PlusPlus random = factory.fromHashOf(id);
    std::vector<noise::PerlinNoise> blocks;
    for (int stack = 0; stack < 2; ++stack) {
        const auto baseLo = static_cast<std::uint64_t>(random.nextLong());
        const auto baseHi = static_cast<std::uint64_t>(random.nextLong());
        for (std::size_t i = 0; i < parameters.amplitudes.size(); ++i) {
            if (!nonZero(parameters.amplitudes[i])) {
                continue;
            }
            const std::string name =
                "octave_" + std::to_string(parameters.firstOctave + static_cast<int>(i));
            const rng::Seed128 salt = rng::seedFromHashOf(name);
            rng::Xoroshiro128PlusPlus octaveRandom{
                rng::Seed128{.lo = baseLo ^ salt.lo, .hi = baseHi ^ salt.hi}};
            blocks.push_back(noise::PerlinNoise::fromRandom(octaveRandom));
        }
    }
    return blocks;
}

// --- the climate chain ------------------------------------------------------
//
// The Nether's temperature and vegetation router entries, hand-rolled over a
// pair of sampling functions so that the noises behind them can be the
// library's or a candidate's. Checked against density::Interpreter by --model.

struct Climate {
    double temperature = 0.0;
    double vegetation = 0.0;
};

/// The chain, written out: shift_a and shift_b over `offset` at the flat_cache
/// corner, then each climate noise at 0.25 * position plus its shift.
///
/// `flat_cache` relocates rather than merely remembers — vanilla fills it once
/// per 4x4 column at y = 0 — but every cell this file samples is already at a
/// multiple of 4 in x and z, so the corner IS the sample point and the
/// relocation is the identity here. Stated because it is an assumption, and
/// asserted by --model rather than by this comment.
template<typename OffsetNoise, typename TemperatureNoise, typename VegetationNoise>
[[nodiscard]] Climate climateAt(const OffsetNoise& offset, const TemperatureNoise& temperature,
                                const VegetationNoise& vegetation, double x, double z) {
    const double shiftX = offset(x * 0.25, 0.0, z * 0.25) * 4.0;
    const double shiftZ = offset(z * 0.25, x * 0.25, 0.0) * 4.0;
    return Climate{.temperature = temperature((x * 0.25) + shiftX, 0.0, (z * 0.25) + shiftZ),
                   .vegetation = vegetation((x * 0.25) + shiftX, 0.0, (z * 0.25) + shiftZ)};
}

[[nodiscard]] biome::ClimateSample sampleOf(const Climate& climate) {
    return biome::ClimateSample{.temperature = climate.temperature,
                                .humidity = climate.vegetation,
                                .continentalness = 0.0,
                                .erosion = 0.0,
                                .depth = 0.0,
                                .weirdness = 0.0};
}

// --- the candidate space ----------------------------------------------------
//
// tools/analysis/legacy-seed-analyze.cpp's, re-implemented here so that this
// file owns no line of that one. The rule INDEX must agree between the two;
// the conformance case asserts it rather than trusting these two headers to
// stay in step.

enum class Base : std::uint8_t { WorldSeed, LcgLong, XoroLo, Scrambled, Zero };
enum class Salt : std::uint8_t {
    Md5FirstBe,
    Md5FirstLe,
    Md5LastBe,
    Md5LastLe,
    Md5LoXorHi,
    Md5LoPlusHi,
    Md5PathFirstBe,
    HashCodeId,
    HashCodePath,
    None
};
enum class Combine : std::uint8_t { Xor, Add, Sub };
enum class Generator : std::uint8_t { Lcg, Xoroshiro };

constexpr std::size_t kBases = 5;
constexpr std::size_t kSalts = 10;
constexpr std::size_t kCombines = 3;
constexpr std::size_t kForks = 3;
constexpr std::size_t kGenerators = 2;
constexpr std::size_t kSeedRules = kBases * kSalts * kCombines * kForks * kGenerators;
constexpr std::size_t kBlockOffsets = 300;

struct SeedRule {
    Base base = Base::WorldSeed;
    Salt salt = Salt::None;
    Combine combine = Combine::Xor;
    int forks = 0;
    Generator generator = Generator::Lcg;
};

[[nodiscard]] SeedRule ruleAt(std::size_t index) {
    SeedRule rule;
    rule.generator = static_cast<Generator>(index % kGenerators);
    index /= kGenerators;
    rule.forks = static_cast<int>(index % kForks);
    index /= kForks;
    rule.combine = static_cast<Combine>(index % kCombines);
    index /= kCombines;
    rule.salt = static_cast<Salt>(index % kSalts);
    index /= kSalts;
    rule.base = static_cast<Base>(index % kBases);
    return rule;
}

[[nodiscard]] std::string describe(const SeedRule& rule) {
    static constexpr std::array<const char*, kBases> kBaseNames{"worldSeed", "lcgLong", "xoroLo",
                                                                "scrambled", "zero"};
    static constexpr std::array<const char*, kSalts> kSaltNames{
        "md5FirstBE",  "md5FirstLE",     "md5LastBE",  "md5LastLE",    "md5LoXorHi",
        "md5LoPlusHi", "md5PathFirstBE", "hashCodeId", "hashCodePath", "none"};
    static constexpr std::array<const char*, kCombines> kCombineNames{"xor", "add", "sub"};
    return std::string{kBaseNames[static_cast<std::size_t>(rule.base)]} + " " +
           kCombineNames[static_cast<std::size_t>(rule.combine)] + " " +
           kSaltNames[static_cast<std::size_t>(rule.salt)] + ", forks " +
           std::to_string(rule.forks) + ", " +
           (rule.generator == Generator::Lcg ? "lcg" : "xoroshiro");
}

[[nodiscard]] std::uint64_t beU64(const hash::Md5Digest& digest, std::size_t at) {
    std::uint64_t value = 0;
    for (std::size_t i = 0; i < 8; ++i) {
        value = (value << 8U) | digest[at + i];
    }
    return value;
}

[[nodiscard]] std::uint64_t leU64(const hash::Md5Digest& digest, std::size_t at) {
    std::uint64_t value = 0;
    for (std::size_t i = 0; i < 8; ++i) {
        value |= static_cast<std::uint64_t>(digest[at + i]) << (8U * i);
    }
    return value;
}

[[nodiscard]] std::int32_t javaHashCode(std::string_view text) {
    std::uint32_t hash = 0;
    for (const char character : text) {
        hash = (hash * 31U) + static_cast<std::uint32_t>(static_cast<unsigned char>(character));
    }
    return static_cast<std::int32_t>(hash);
}

[[nodiscard]] std::uint64_t saltFor(Salt salt, std::string_view id) {
    const std::size_t colon = id.find(':');
    const std::string_view path = colon == std::string_view::npos ? id : id.substr(colon + 1);
    const hash::Md5Digest digest = hash::md5(id);
    const hash::Md5Digest pathDigest = hash::md5(path);
    switch (salt) {
        case Salt::Md5FirstBe:
            return beU64(digest, 0);
        case Salt::Md5FirstLe:
            return leU64(digest, 0);
        case Salt::Md5LastBe:
            return beU64(digest, 8);
        case Salt::Md5LastLe:
            return leU64(digest, 8);
        case Salt::Md5LoXorHi:
            return beU64(digest, 0) ^ beU64(digest, 8);
        case Salt::Md5LoPlusHi:
            return beU64(digest, 0) + beU64(digest, 8);
        case Salt::Md5PathFirstBe:
            return beU64(pathDigest, 0);
        case Salt::HashCodeId:
            return static_cast<std::uint64_t>(static_cast<std::int64_t>(javaHashCode(id)));
        case Salt::HashCodePath:
            return static_cast<std::uint64_t>(static_cast<std::int64_t>(javaHashCode(path)));
        case Salt::None:
            return 0;
    }
    return 0;
}

[[nodiscard]] std::uint64_t baseFor(Base base, std::int64_t worldSeed) {
    switch (base) {
        case Base::WorldSeed:
            return static_cast<std::uint64_t>(worldSeed);
        case Base::LcgLong: {
            rng::JavaRandom random{worldSeed};
            return static_cast<std::uint64_t>(random.nextLong());
        }
        case Base::XoroLo: {
            rng::Xoroshiro128PlusPlus random{worldSeed};
            return static_cast<std::uint64_t>(random.nextLong());
        }
        case Base::Scrambled:
            return (static_cast<std::uint64_t>(worldSeed) ^ UINT64_C(0x5DEECE66D)) &
                   ((UINT64_C(1) << 48U) - 1);
        case Base::Zero:
            return 0;
    }
    return 0;
}

[[nodiscard]] std::int64_t seedFor(const SeedRule& rule, std::int64_t worldSeed,
                                   std::string_view id) {
    const std::uint64_t base = baseFor(rule.base, worldSeed);
    const std::uint64_t salt = saltFor(rule.salt, id);
    std::uint64_t seed = 0;
    switch (rule.combine) {
        case Combine::Xor:
            seed = base ^ salt;
            break;
        case Combine::Add:
            seed = base + salt;
            break;
        case Combine::Sub:
            seed = base - salt;
            break;
    }
    for (int i = 0; i < rule.forks; ++i) {
        rng::JavaRandom random{static_cast<std::int64_t>(seed)};
        seed = static_cast<std::uint64_t>(random.nextLong());
    }
    return static_cast<std::int64_t>(seed);
}

[[nodiscard]] std::vector<noise::PerlinNoise> blocksFor(const SeedRule& rule, std::int64_t seed,
                                                        std::size_t needed) {
    std::vector<noise::PerlinNoise> blocks;
    blocks.reserve(needed);
    if (rule.generator == Generator::Lcg) {
        rng::JavaRandom random{seed};
        for (std::size_t i = 0; i < needed; ++i) {
            blocks.push_back(noise::PerlinNoise::fromRandom(random));
        }
    } else {
        rng::Xoroshiro128PlusPlus random{seed};
        for (std::size_t i = 0; i < needed; ++i) {
            blocks.push_back(noise::PerlinNoise::fromRandom(random));
        }
    }
    return blocks;
}

// --- the three noises in play -----------------------------------------------

struct ClimateNoises {
    density::NoiseParameters offset;
    density::NoiseParameters temperature;
    density::NoiseParameters vegetation;
    Layout offsetLayout;
    Layout temperatureLayout;
    Layout vegetationLayout;
};

constexpr std::string_view kOffsetId = "minecraft:offset";
constexpr std::string_view kTemperatureId = "minecraft:temperature";
constexpr std::string_view kVegetationId = "minecraft:vegetation";

[[nodiscard]] density::NoiseParameters parametersOf(const data::Pack& pack, std::string_view id) {
    const data::ResourceLocation location = data::ResourceLocation::parse(id);
    const data::PackEntry* entry = pack.find(data::Registry::Noise, location);
    if (entry == nullptr) {
        std::fprintf(stderr, "the pack does not define worldgen/noise %s\n",
                     std::string{id}.c_str());
        std::exit(1);
    }
    return density::NoiseParameters::fromJson(entry->json, location);
}

[[nodiscard]] ClimateNoises climateNoisesOf(const data::Pack& pack) {
    ClimateNoises noises;
    noises.offset = parametersOf(pack, kOffsetId);
    noises.temperature = parametersOf(pack, kTemperatureId);
    noises.vegetation = parametersOf(pack, kVegetationId);
    noises.offsetLayout = layoutFor(noises.offset);
    noises.temperatureLayout = layoutFor(noises.temperature);
    noises.vegetationLayout = layoutFor(noises.vegetation);
    return noises;
}

// --- scoring ----------------------------------------------------------------

struct Tally {
    std::size_t cells = 0;
    std::size_t agree = 0;
    std::size_t interiorCells = 0;
    std::size_t interiorAgree = 0;
    std::vector<std::size_t> vanillaCounts;
    std::vector<std::size_t> ourCounts;

    explicit Tally(std::size_t biomes) : vanillaCounts(biomes, 0), ourCounts(biomes, 0) {}

    void add(std::uint16_t vanilla, std::uint16_t ours, bool boundary) {
        ++cells;
        ++vanillaCounts[vanilla];
        ++ourCounts[ours];
        const bool same = vanilla == ours;
        if (same) {
            ++agree;
        }
        if (!boundary) {
            ++interiorCells;
            if (same) {
                ++interiorAgree;
            }
        }
    }

    void absorb(const Tally& other) {
        cells += other.cells;
        agree += other.agree;
        interiorCells += other.interiorCells;
        interiorAgree += other.interiorAgree;
        for (std::size_t i = 0; i < vanillaCounts.size(); ++i) {
            vanillaCounts[i] += other.vanillaCounts[i];
            ourCounts[i] += other.ourCounts[i];
        }
    }

    [[nodiscard]] double rate() const {
        return cells == 0 ? 0.0 : static_cast<double>(agree) / static_cast<double>(cells);
    }

    /// The agreement two INDEPENDENT labelings with these marginals would
    /// reach. A bare percentage over five unequal biomes says nothing without
    /// it.
    [[nodiscard]] double chanceBaseline() const {
        if (cells == 0) {
            return 0.0;
        }
        double sum = 0.0;
        for (std::size_t i = 0; i < vanillaCounts.size(); ++i) {
            sum += (static_cast<double>(vanillaCounts[i]) / static_cast<double>(cells)) *
                   (static_cast<double>(ourCounts[i]) / static_cast<double>(cells));
        }
        return sum;
    }
};

/// Scores one candidate (seed rule, block offset) over one world.
[[nodiscard]] Tally scoreCandidate(const ClimateNoises& noises, const biome::ParameterList& table,
                                   const BiomeIndex& biomes, const World& world,
                                   const std::vector<noise::PerlinNoise>& offsetBlocks,
                                   const std::vector<noise::PerlinNoise>& temperatureBlocks,
                                   const std::vector<noise::PerlinNoise>& vegetationBlocks,
                                   std::size_t block) {
    Tally tally{biomes.size()};
    const auto offset = [&](double x, double y, double z) {
        return sampleNormal(noises.offsetLayout, offsetBlocks, block, x, y, z);
    };
    const auto temperature = [&](double x, double y, double z) {
        return sampleNormal(noises.temperatureLayout, temperatureBlocks, block, x, y, z);
    };
    const auto vegetation = [&](double x, double y, double z) {
        return sampleNormal(noises.vegetationLayout, vegetationBlocks, block, x, y, z);
    };
    for (const Cell& cell : world.cells) {
        const Climate climate = climateAt(offset, temperature, vegetation,
                                          static_cast<double>(cell.x), static_cast<double>(cell.z));
        const std::optional<std::uint16_t> chosen =
            biomes.find(table.find(sampleOf(climate)).toString());
        tally.add(cell.biome, chosen.value_or(0), cell.boundary);
    }
    return tally;
}

struct Result {
    std::size_t seedRule = 0;
    std::size_t block = 0;
    std::size_t agreed = 0;
};

