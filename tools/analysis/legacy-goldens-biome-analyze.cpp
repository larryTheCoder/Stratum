// NOLINTNEXTLINE(bugprone-exception-escape): a throw here is a fixture fault
// and the message is the point; there is nothing to recover to.
int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr,
                     "usage: %s <fixtures-dir> "
                     "--preset|--control|--attribute|--ties|--quantize|--model|--modern|--boundary|"
                     "--scan|--split|"
                     "--null-full [draws|all] [draw-seed]|"
                     "--candidate <rule> <block> [zero-shift]\n",
                     argv[0]);
        return 2;
    }
    const std::filesystem::path fixtures{argv[1]};
    const std::string mode{argv[2]};

    const std::filesystem::path tree = findWorldgenTree(fixtures);
    const std::filesystem::path netherTable =
        findUnder(fixtures, "nether.json", "biome_parameters");
    const std::filesystem::path overworldTable =
        findUnder(fixtures, "overworld.json", "biome_parameters");
    if (tree.empty() || netherTable.empty() || overworldTable.empty()) {
        std::fprintf(stderr,
                     "no extracted vanilla worldgen or biome_parameters under %s — Mojang-derived "
                     "and never committed (SPEC §12). Generate them with: tools/fetch-vanilla\n",
                     fixtures.string().c_str());
        return 77;
    }

    const auto readTable = [](const std::filesystem::path& path, std::string_view id) {
        std::ifstream stream(path);
        return biome::ParameterList::fromJson(nlohmann::json::parse(stream),
                                              data::ResourceLocation::parse(id));
    };
    const biome::ParameterList nether = readTable(netherTable, "minecraft:nether");
    const BiomeIndex biomes{nether};

    if (mode == "--preset") {
        std::printf("nether multi_noise parameter list: %zu entries, from the server's own data "
                    "generator (--reports), kept at %s\n",
                    nether.size(), netherTable.string().c_str());
        std::printf("  the pack ships only {\"preset\": \"minecraft:nether\"}; these numbers are "
                    "OBSERVED SERVER OUTPUT, not read out of the jar\n");
        for (const auto& entry : nether.entries()) {
            const auto& p = entry.parameters;
            std::printf("  %-28s T[%+.4f,%+.4f] H[%+.4f,%+.4f] C[%+.4f,%+.4f] E[%+.4f,%+.4f] "
                        "D[%+.4f,%+.4f] W[%+.4f,%+.4f] offset %+.4f\n",
                        entry.biome.toString().c_str(), p.temperature.min, p.temperature.max,
                        p.humidity.min, p.humidity.max, p.continentalness.min,
                        p.continentalness.max, p.erosion.min, p.erosion.max, p.depth.min,
                        p.depth.max, p.weirdness.min, p.weirdness.max, p.offset);
        }
        return 0;
    }

    const data::Pack pack = data::Pack::open(tree);
    stratum::settings::LoadedSettings loaded = stratum::settings::loadAll(pack);
    const auto& netherSettings =
        loaded.settings.at(data::ResourceLocation::parse("minecraft:nether"));
    const ClimateNoises noises = climateNoisesOf(pack);

    // The noises the Nether's climate actually reaches, from the library's own
    // graph walk rather than from this file's idea of the router.
    std::vector<data::ResourceLocation> wanted = loaded.graph.noisesReachableFrom(
        netherSettings.router.at(stratum::settings::RouterEntry::Temperature));
    for (const auto& id : loaded.graph.noisesReachableFrom(
             netherSettings.router.at(stratum::settings::RouterEntry::Vegetation))) {
        if (std::find(wanted.begin(), wanted.end(), id) == wanted.end()) {
            wanted.push_back(id);
        }
    }

    // --- the decoder control, on the overworld ------------------------------
    //
    // THREE ARMS, because two are not enough. The positive arm says the
    // decoder can see a correct seeding. The negative arm says a WRONG seeding
    // does not survive it. And the third arm is what makes the second
    // readable: a wrong seeding is not a random relabeling of the map, because
    // both arms share the coordinates, the y structure and vanilla's own biome
    // marginals, so the null for "a different world's labels against this
    // world's" sits well above the null for "two independent draws". That null
    // is measured rather than modelled, by scoring vanilla's OWN goldens at one
    // seed against vanilla's own goldens at another, at matching coordinates —
    // two real worlds, every shared structure intact, nothing in common but
    // the geometry.
    if (mode == "--control") {
        const biome::ParameterList overworld = readTable(overworldTable, "minecraft:overworld");
        const auto& settings =
            loaded.settings.at(data::ResourceLocation::parse("minecraft:overworld"));
        // EVERY FOURTH CHUNK OF THE WHOLE REGION, not a corner of it, and the
        // distinction is the one the Nether case already had to learn: over a
        // 32x32-block corner a world is essentially one biome, so "agreement"
        // there measures whether two maps happen to share a dominant biome and
        // the effective sample size is the number of REGIONS, not the number of
        // cells. Measured: at a 2x2-chunk corner the wrong-seed arm scored
        // 10.56% against a 3.87% cross-world null and looked like a control
        // failure, which was the sampling and not the decoder.
        constexpr std::int32_t kChunkStride = 4;
        // Four heights rather than every section: the overworld's biome does
        // vary down a column — that is what `depth` is for — so the sample has
        // to span y, but 24 sections a chunk buys correlated cells at 24 times
        // the cost.
        constexpr std::array<std::int32_t, 4> kHeights{-48, 16, 64, 112};

        // Per seed, the stored labels in one fixed coordinate order, so the
        // cross-world arm can pair them up cell for cell.
        std::vector<std::vector<std::string>> goldenPerSeed;
        std::size_t cells = 0;
        std::size_t positive = 0;
        std::size_t negative = 0;
        // Keyed by seed and horizontal position, not counted: the residual
        // below turns out to be whole COLUMNS that disagree at every height,
        // and a count of cells would report each of them four times.
        std::map<std::string, std::string> misses;
        for (const std::int64_t seed : kAllSeeds) {
            const std::filesystem::path region = regionOf(fixtures, seed, "overworld");
            if (region.empty()) {
                continue;
            }
            const auto build = [&](std::int64_t with) {
                return density::NoiseRegistry::create(pack, loaded.graph.referencedNoises(), with,
                                                      density::RandomSource::Xoroshiro);
            };
            const auto right = build(seed);
            const auto wrong = build(seed + 1);
            const density::CellGeometry geometry{.width = settings.geometry.cellWidth(),
                                                 .height = settings.geometry.cellHeight()};
            const density::Interpreter rightInterpreter(loaded.graph, right, geometry);
            const density::Interpreter wrongInterpreter(loaded.graph, wrong, geometry);
            const region::RegionFile file = region::RegionFile::open(region);
            std::vector<std::string> golden;
            for (std::int32_t chunkZ = 0; chunkZ < region::kChunksPerAxis; chunkZ += kChunkStride) {
                for (std::int32_t chunkX = 0; chunkX < region::kChunksPerAxis;
                     chunkX += kChunkStride) {
                    if (!file.hasChunk(chunkX, chunkZ)) {
                        continue;
                    }
                    const chunk::Chunk decoded =
                        chunk::Chunk::decode(nbt::read(file.readChunk(chunkX, chunkZ)).root);
                    for (const auto& section : decoded.sections()) {
                        if (section.biomes.empty()) {
                            continue;
                        }
                        for (int cellY = 0; cellY < 4; ++cellY) {
                            const std::int32_t y = (section.y * 16) + (cellY * 4);
                            if (std::find(kHeights.begin(), kHeights.end(), y) == kHeights.end()) {
                                continue;
                            }
                            for (int cellZ = 0; cellZ < 4; ++cellZ) {
                                for (int cellX = 0; cellX < 4; ++cellX) {
                                    const std::size_t index =
                                        (static_cast<std::size_t>(cellY) * 16U) +
                                        (static_cast<std::size_t>(cellZ) * 4U) +
                                        static_cast<std::size_t>(cellX);
                                    if (index >= section.biomes.size()) {
                                        continue;
                                    }
                                    const std::string& stored =
                                        section.biomePalette[section.biomes[index]];
                                    const density::Point at{.x = (chunkX * 16) + (cellX * 4),
                                                            .y = y,
                                                            .z = (chunkZ * 16) + (cellZ * 4)};
                                    const auto evaluate = [&](const density::Interpreter& with) {
                                        using stratum::settings::RouterEntry;
                                        return biome::ClimateSample{
                                            .temperature = with.evaluate(
                                                settings.router.at(RouterEntry::Temperature), at),
                                            .humidity = with.evaluate(
                                                settings.router.at(RouterEntry::Vegetation), at),
                                            .continentalness = with.evaluate(
                                                settings.router.at(RouterEntry::Continents), at),
                                            .erosion = with.evaluate(
                                                settings.router.at(RouterEntry::Erosion), at),
                                            .depth = with.evaluate(
                                                settings.router.at(RouterEntry::Depth), at),
                                            .weirdness = with.evaluate(
                                                settings.router.at(RouterEntry::Ridges), at)};
                                    };
                                    ++cells;
                                    const std::string chosen =
                                        overworld.find(evaluate(rightInterpreter)).toString();
                                    if (chosen == stored) {
                                        ++positive;
                                    } else {
                                        std::string where = std::to_string(seed);
                                        where.append(" (").append(std::to_string(at.x));
                                        where.append(",").append(std::to_string(at.z));
                                        where.append(")");
                                        std::string what = stored;
                                        what.append(" -> ").append(chosen);
                                        misses[where] = what;
                                    }
                                    if (overworld.find(evaluate(wrongInterpreter)).toString() ==
                                        stored) {
                                        ++negative;
                                    }
                                    golden.push_back(stored);
                                }
                            }
                        }
                    }
                }
            }
            goldenPerSeed.push_back(std::move(golden));
        }
        if (goldenPerSeed.empty() || cells == 0) {
            std::fprintf(stderr, "no golden overworld regions under %s\n",
                         fixtures.string().c_str());
            return 77;
        }

        // The null: vanilla's own map at one seed against vanilla's own map at
        // another, cell for cell, over every pair of distinct worlds.
        std::size_t pairCells = 0;
        std::size_t pairAgree = 0;
        std::size_t pairs = 0;
        for (std::size_t a = 0; a < goldenPerSeed.size(); ++a) {
            for (std::size_t b = a + 1; b < goldenPerSeed.size(); ++b) {
                if (goldenPerSeed[a].size() != goldenPerSeed[b].size()) {
                    continue;
                }
                ++pairs;
                for (std::size_t i = 0; i < goldenPerSeed[a].size(); ++i) {
                    ++pairCells;
                    if (goldenPerSeed[a][i] == goldenPerSeed[b][i]) {
                        ++pairAgree;
                    }
                }
            }
        }
        const double positiveRate = static_cast<double>(positive) / static_cast<double>(cells);
        const double negativeRate = static_cast<double>(negative) / static_cast<double>(cells);
        const double nullRate =
            pairCells == 0 ? 0.0 : static_cast<double>(pairAgree) / static_cast<double>(pairCells);
        std::printf("control (overworld, %zu regions, %zu cells)\n", goldenPerSeed.size(), cells);
        std::printf("  worldSeed        %zu/%zu = %.4f%%\n", positive, cells, 100.0 * positiveRate);
        std::printf("  worldSeed + 1    %zu/%zu = %.4f%%\n", negative, cells, 100.0 * negativeRate);
        std::printf("  null (vanilla vs vanilla, %zu world pairs)  %zu/%zu = %.4f%%\n", pairs,
                    pairAgree, pairCells, 100.0 * nullRate);
        std::printf("  the positive arm's residual is %zu column(s), each wrong at every "
                    "sampled height — a horizontal disagreement, not a depth one:\n",
                    misses.size());
        for (const auto& [where, what] : misses) {
            std::printf("    seed %-40s %s\n", where.c_str(), what.c_str());
        }
        // The positive arm has to be EXACT, and the negative arm has to sit at
        // the null a genuinely unrelated world reaches. Neither alone is a
        // control: without the first, "no survivor" says the decoder is blind;
        // without the second, it says the decoder accepts anything.
        // NOT "== cells", and the difference is a finding rather than a
        // slackened threshold. The [biome] conformance cases report the
        // overworld biome source as EXACT, and over their sample it is: a
        // 64x64-block corner of four regions, 98304 cells, no miss. Spread the
        // same decode over the whole 512x512 of eight regions and five columns
        // out of 8192 come back wrong — 0.061% of cells, each of them wrong at
        // every sampled height, so a horizontal disagreement and not a depth
        // one. That is a residual of the biome source, not of this readback,
        // and it is named here with its seeds and coordinates rather than
        // rounded away. It is far too small to matter to what follows: the
        // separation this control has to establish is 99.94% against 6.37%.
        if (positiveRate < 0.999) {
            std::fprintf(stderr,
                         "control FAILED: the decoder recovers the modern seeding on its own "
                         "goldens at only %.4f%%\n",
                         100.0 * positiveRate);
            return 1;
        }
        if (negativeRate > nullRate + 0.02) {
            std::fprintf(stderr,
                         "control FAILED: the decoder scores worldSeed + 1 at %.4f%%, above the "
                         "%.4f%% an unrelated vanilla world reaches, so something other than the "
                         "seeding is doing the work\n",
                         100.0 * negativeRate, 100.0 * nullRate);
            return 1;
        }
        std::printf("control passed: this decoder recovers a correct seeding at %.4f%% and puts a "
                    "wrong one at the null (%.4f%% against the %.4f%% an unrelated vanilla world "
                    "reaches)\n",
                    100.0 * positiveRate, 100.0 * negativeRate, 100.0 * nullRate);
        return 0;
    }

    if (mode == "--attribute") {
        return runAttribute(fixtures, pack, loaded,
                            readTable(overworldTable, "minecraft:overworld"));
    }

    if (mode == "--ties") {
        return runTies(fixtures, pack, loaded, readTable(overworldTable, "minecraft:overworld"));
    }

    if (mode == "--quantize") {
        return runQuantize(fixtures, pack, loaded,
                           readTable(overworldTable, "minecraft:overworld"));
    }

    // --- the forward-model control, on the Nether ---------------------------
    if (mode == "--model") {
        constexpr std::int64_t kSeed = 42;
        const auto registry =
            density::NoiseRegistry::create(pack, wanted, kSeed, density::RandomSource::Xoroshiro);
        const density::Interpreter interpreter(
            loaded.graph, registry,
            density::CellGeometry{.width = netherSettings.geometry.cellWidth(),
                                  .height = netherSettings.geometry.cellHeight()});
        const auto& libraryOffset = registry.get(data::ResourceLocation::parse(kOffsetId));
        const auto& libraryTemperature =
            registry.get(data::ResourceLocation::parse(kTemperatureId));
        const auto& libraryVegetation = registry.get(data::ResourceLocation::parse(kVegetationId));
        const auto offsetBlocks = modernBlocksFor(noises.offset, kOffsetId, kSeed);
        const auto temperatureBlocks = modernBlocksFor(noises.temperature, kTemperatureId, kSeed);
        const auto vegetationBlocks = modernBlocksFor(noises.vegetation, kVegetationId, kSeed);

        std::size_t points = 0;
        std::size_t stackIdentical = 0;
        std::size_t chainIdentical = 0;
        std::size_t wholeIdentical = 0;
        const auto bits = [](double value) { return std::bit_cast<std::uint64_t>(value); };
        for (std::int32_t z = 0; z < 512; z += 16) {
            for (std::int32_t x = 0; x < 512; x += 16) {
                const auto fx = static_cast<double>(x);
                const auto fz = static_cast<double>(z);
                ++points;

                // stack: this file's sampleNormal against the library's
                // NormalNoise, for all three noises, at a point each of them
                // is actually read at.
                const bool stackOk =
                    bits(sampleNormal(noises.offsetLayout, offsetBlocks, 0, fx * 0.25, 0.0,
                                      fz * 0.25)) ==
                        bits(libraryOffset.sample(fx * 0.25, 0.0, fz * 0.25)) &&
                    bits(sampleNormal(noises.temperatureLayout, temperatureBlocks, 0, fx * 0.25,
                                      0.0, fz * 0.25)) ==
                        bits(libraryTemperature.sample(fx * 0.25, 0.0, fz * 0.25)) &&
                    bits(sampleNormal(noises.vegetationLayout, vegetationBlocks, 0, fx * 0.25, 0.0,
                                      fz * 0.25)) ==
                        bits(libraryVegetation.sample(fx * 0.25, 0.0, fz * 0.25));
                if (stackOk) {
                    ++stackIdentical;
                }

                const density::Point at{.x = x, .y = kNetherSampleY, .z = z};
                using stratum::settings::RouterEntry;
                const double routerTemperature =
                    interpreter.evaluate(netherSettings.router.at(RouterEntry::Temperature), at);
                const double routerVegetation =
                    interpreter.evaluate(netherSettings.router.at(RouterEntry::Vegetation), at);

                // chain: this file's shift/shifted_noise wiring over the
                // LIBRARY's noises, against the Interpreter's own evaluation.
                const Climate viaLibrary = climateAt(
                    [&](double a, double b, double c) { return libraryOffset.sample(a, b, c); },
                    [&](double a, double b, double c) {
                        return libraryTemperature.sample(a, b, c);
                    },
                    [&](double a, double b, double c) { return libraryVegetation.sample(a, b, c); },
                    fx, fz);
                if (bits(viaLibrary.temperature) == bits(routerTemperature) &&
                    bits(viaLibrary.vegetation) == bits(routerVegetation)) {
                    ++chainIdentical;
                }

                // whole: the composition — this file's chain over this file's
                // stacks, which is exactly what the scan runs.
                const Climate viaModel = climateAt(
                    [&](double a, double b, double c) {
                        return sampleNormal(noises.offsetLayout, offsetBlocks, 0, a, b, c);
                    },
                    [&](double a, double b, double c) {
                        return sampleNormal(noises.temperatureLayout, temperatureBlocks, 0, a, b,
                                            c);
                    },
                    [&](double a, double b, double c) {
                        return sampleNormal(noises.vegetationLayout, vegetationBlocks, 0, a, b, c);
                    },
                    fx, fz);
                if (bits(viaModel.temperature) == bits(routerTemperature) &&
                    bits(viaModel.vegetation) == bits(routerVegetation)) {
                    ++wholeIdentical;
                }
            }
        }
        std::printf("forward model at seed 42, %zu points\n", points);
        std::printf("  stack (sampleNormal vs NormalNoise, 3 noises)  %zu/%zu\n", stackIdentical,
                    points);
        std::printf("  chain (shift wiring vs Interpreter)            %zu/%zu\n", chainIdentical,
                    points);
        std::printf("  whole (what the scan runs vs Interpreter)      %zu/%zu\n", wholeIdentical,
                    points);
        if (stackIdentical != points || chainIdentical != points || wholeIdentical != points) {
            std::fprintf(stderr, "forward model FAILED: the scan's model is not the function the "
                                 "library computes, so its null and its scores are about "
                                 "something else\n");
            return 1;
        }
        std::printf("forward model passed\n");
        return 0;
    }

    // --- everything below reads the Nether goldens --------------------------
    const auto loadWorlds = [&](std::span<const std::int64_t> seeds, std::int32_t stride) {
        std::vector<World> worlds;
        for (const std::int64_t seed : seeds) {
            const std::filesystem::path region = regionOf(fixtures, seed, "nether");
            if (region.empty()) {
                continue;
            }
            worlds.push_back(readNetherWorld(region, seed, biomes, stride));
        }
        return worlds;
    };

    if (mode == "--modern") {
        // The number already on record: 8873/32768 = 27.08% against a 30.23%
        // baseline, over ALL EIGHT seeds, which is how
        // vanilla_legacy_nether_climate_gap_test.cpp measured it. Reproduced
        // here through THIS file's chain rather than through the Interpreter,
        // so that agreeing with it is evidence about this file.
        const std::vector<World> worlds = loadWorlds(kAllSeeds, kNetherChunkStride);
        if (worlds.empty()) {
            std::fprintf(stderr, "no golden nether regions under %s\n", fixtures.string().c_str());
            return 77;
        }
        Tally overall{biomes.size()};
        std::size_t varying = 0;
        for (const World& world : worlds) {
            varying += world.varyingWithY;
            const auto offsetBlocks = modernBlocksFor(noises.offset, kOffsetId, world.seed);
            const auto temperatureBlocks =
                modernBlocksFor(noises.temperature, kTemperatureId, world.seed);
            const auto vegetationBlocks =
                modernBlocksFor(noises.vegetation, kVegetationId, world.seed);
            const Tally tally = scoreCandidate(noises, nether, biomes, world, offsetBlocks,
                                               temperatureBlocks, vegetationBlocks, 0);
            std::printf("  seed %-21lld %5zu/%5zu = %6.2f%%  baseline %6.2f%%\n",
                        static_cast<long long>(world.seed), tally.agree, tally.cells,
                        100.0 * tally.rate(), 100.0 * tally.chanceBaseline());
            overall.absorb(tally);
        }
        std::printf("modern derivation on the nether, %zu regions: %zu/%zu = %.2f%%, chance "
                    "baseline %.2f%%; %zu column(s) varying with y\n",
                    worlds.size(), overall.agree, overall.cells, 100.0 * overall.rate(),
                    100.0 * overall.chanceBaseline(), varying);
        for (std::size_t i = 0; i < biomes.size(); ++i) {
            std::printf("    %-28s vanilla %6zu, modern rule %6zu\n",
                        biomes.nameOf(static_cast<std::uint16_t>(i)).c_str(),
                        overall.vanillaCounts[i], overall.ourCounts[i]);
        }
        return 0;
    }

    if (mode == "--boundary") {
        const std::vector<World> worlds = loadWorlds(kDistinctSeeds, kNetherChunkStride);
        if (worlds.empty()) {
            std::fprintf(stderr, "no golden nether regions under %s\n", fixtures.string().c_str());
            return 77;
        }
        std::size_t cells = 0;
        std::size_t boundary = 0;
        std::vector<std::size_t> counts(biomes.size(), 0);
        for (const World& world : worlds) {
            for (const Cell& cell : world.cells) {
                ++cells;
                ++counts[cell.biome];
                if (cell.boundary) {
                    ++boundary;
                }
            }
        }
        std::printf("denominator: %zu cells over %zu independent worlds\n", cells, worlds.size());
        std::printf("  boundary-adjacent (a 4-neighbour inside the same chunk carries a "
                    "different biome): %zu (%.2f%%)\n",
                    boundary, 100.0 * static_cast<double>(boundary) / static_cast<double>(cells));
        std::printf("  interior: %zu (%.2f%%)\n", cells - boundary,
                    100.0 * static_cast<double>(cells - boundary) / static_cast<double>(cells));
        double selfAgreement = 0.0;
        for (std::size_t i = 0; i < biomes.size(); ++i) {
            const double share = static_cast<double>(counts[i]) / static_cast<double>(cells);
            selfAgreement += share * share;
            std::printf("    %-28s %6zu (%5.2f%%)\n",
                        biomes.nameOf(static_cast<std::uint16_t>(i)).c_str(), counts[i],
                        100.0 * share);
        }
        std::printf("  a labeling drawn independently WITH VANILLA'S OWN MARGINALS would agree "
                    "%.2f%% of the time — that is the ceiling on what a wrong seeding has to "
                    "beat, and the floor under every number this readback prints\n",
                    100.0 * selfAgreement);
        return 0;
    }

    const bool candidateMode = mode == "--candidate";
    const bool splitMode = mode == "--split";
    const bool nullFullMode = mode == "--null-full";
    if (!candidateMode && !splitMode && !nullFullMode && mode != "--scan") {
        std::fprintf(stderr, "unknown mode %s\n", mode.c_str());
        return 2;
    }
    const Shift shift = splitMode ? Shift::Zero : Shift::FromOffset;

    // Stage 1 subsamples chunks hard: the full stride-2 sample is 4096 cells a
    // world and 270,000 candidates over it is not a run anyone would finish.
    // Stage 2 re-scores the survivors over the full sample, so the reported
    // number for anything that matters has the full denominator.
    constexpr std::int32_t kScanStride = 8;
    const std::vector<World> coarse = loadWorlds(kDistinctSeeds, kScanStride);
    if (coarse.empty()) {
        std::fprintf(stderr, "no golden nether regions under %s\n", fixtures.string().c_str());
        return 77;
    }
    std::size_t coarseCells = 0;
    for (const World& world : coarse) {
        coarseCells += world.cells.size();
    }

    const std::size_t blocksNeeded =
        kBlockOffsets +
        std::max({noises.offsetLayout.blocksPerNoise, noises.temperatureLayout.blocksPerNoise,
                  noises.vegetationLayout.blocksPerNoise});

    if (candidateMode) {
        if (argc < 5) {
            std::fprintf(stderr, "--candidate needs a rule index and a block offset\n");
            return 2;
        }
        const auto ruleIndex = static_cast<std::size_t>(std::strtoull(argv[3], nullptr, 10));
        const auto block = static_cast<std::size_t>(std::strtoull(argv[4], nullptr, 10));
        if (ruleIndex >= kSeedRules || block >= kBlockOffsets) {
            std::fprintf(stderr, "rule must be < %zu and block < %zu\n", kSeedRules, kBlockOffsets);
            return 2;
        }
        // A fifth argument of `zero-shift` scores that one candidate the way
        // --split scores all 270,000. It exists so the Shift::Zero path has a
        // caller that costs a third of a second: --split itself is a second
        // full scan and no CTest case can afford it, and an arm nothing runs
        // is how the `--split` sentence in this file's header came to describe
        // a mode that did not exist.
        const Shift candidateShift =
            (argc >= 6 && std::string{argv[5]} == "zero-shift") ? Shift::Zero : Shift::FromOffset;
        const SeedRule rule = ruleAt(ruleIndex);
        const std::vector<World> full = loadWorlds(kDistinctSeeds, kNetherChunkStride);
        Tally overall{biomes.size()};
        for (const World& world : full) {
            const auto offsetBlocks =
                blocksFor(rule, seedFor(rule, world.seed, kOffsetId), blocksNeeded);
            const auto temperatureBlocks =
                blocksFor(rule, seedFor(rule, world.seed, kTemperatureId), blocksNeeded);
            const auto vegetationBlocks =
                blocksFor(rule, seedFor(rule, world.seed, kVegetationId), blocksNeeded);
            overall.absorb(scoreCandidate(noises, nether, biomes, world, offsetBlocks,
                                          temperatureBlocks, vegetationBlocks, block,
                                          candidateShift));
        }
        std::printf("rule %zu block %zu (%s)%s: %zu/%zu = %.2f%%, chance baseline %.2f%%; "
                    "interior only %zu/%zu = %.2f%%\n",
                    ruleIndex, block, describe(rule).c_str(),
                    candidateShift == Shift::Zero ? " with the shift held at zero" : "",
                    overall.agree, overall.cells, 100.0 * overall.rate(),
                    100.0 * overall.chanceBaseline(), overall.interiorAgree, overall.interiorCells,
                    overall.interiorCells == 0
                        ? 0.0
                        : 100.0 * static_cast<double>(overall.interiorAgree) /
                              static_cast<double>(overall.interiorCells));
        return 0;
    }

    // --- the null at the FULL denominator ------------------------------------
    //
    // The scan's null is a stage-1 object: 270,000 candidates over 1536 cells.
    // Its headline score is a stage-2 object: one candidate over 24576. Those
    // two numbers are not comparable, and the maximum of the first is the worst
    // possible yardstick for the second — it is an extreme-value statistic over
    // a quarter-million draws at a sixteenth of the sample, so it carries that
    // sample's variance and a selection bias on top, and (this is the part that
    // makes it circular rather than merely mismatched) the candidate that
    // ATTAINS it is a member of the top table it is being held up against.
    // This mode measures the null where the answer is quoted: the same
    // candidates, scored over every cell the oracle offers.
    //
    // `all` enumerates the whole space at that denominator. It is about an
    // hour, and it buys two things a sample does not: the distribution is the
    // space's own rather than an estimate of it, and the maximum it reports is
    // the best score ANYWHERE in the space — not the best of the 32 that a
    // 1536-cell stage 1 happened to promote. "The best we found" and "the best
    // there is" are different claims, and the gap between this maximum and the
    // scan's stage-2 winner is the size of stage 1's selection noise.
    if (nullFullMode) {
        constexpr std::size_t kDefaultDraws = 512;
        constexpr std::int64_t kDefaultDrawSeed = 20260919;
        const std::string howMany{argc >= 4 ? argv[3] : ""};
        const bool everything = howMany == "all";
        const std::size_t draws = [&]() -> std::size_t {
            if (everything) {
                return kSeedRules * kBlockOffsets;
            }
            if (argc >= 4) {
                return static_cast<std::size_t>(std::strtoull(argv[3], nullptr, 10));
            }
            return kDefaultDraws;
        }();
        const std::int64_t drawSeed =
            argc >= 5 ? static_cast<std::int64_t>(std::strtoll(argv[4], nullptr, 10))
                      : kDefaultDrawSeed;
        if (draws == 0) {
            std::fprintf(stderr, "--null-full needs at least one draw, or `all`\n");
            return 2;
        }
        const std::vector<World> full = loadWorlds(kDistinctSeeds, kNetherChunkStride);
        std::size_t fullCells = 0;
        for (const World& world : full) {
            fullCells += world.cells.size();
        }
        if (everything) {
            std::printf("null at the full denominator: EVERY one of the %zu candidates, each "
                        "scored over %zu cells (%zu worlds)\n",
                        draws, fullCells, full.size());
        } else {
            std::printf("null at the full denominator: %zu candidates drawn uniformly from %zu, "
                        "each scored over %zu cells (%zu worlds)\n",
                        draws, kSeedRules * kBlockOffsets, fullCells, full.size());
            std::printf("  draws come from the project's Java LCG at seed %lld, so this run "
                        "reproduces exactly\n",
                        static_cast<long long>(drawSeed));
        }

        std::vector<std::size_t> histogram(fullCells + 1, 0);
        std::size_t worst = 0;
        Result worstAt;
        rng::JavaRandom draw{drawSeed};

        // Enumerating reuses one rule's Perlin blocks across its 300 block
        // offsets, exactly as stage 1 does; sampling cannot, because
        // consecutive draws are unrelated rules.
        const auto record = [&](std::size_t ruleIndex, std::size_t block, std::size_t agreed) {
            ++histogram[agreed];
            if (agreed > worst) {
                worst = agreed;
                worstAt = Result{.seedRule = ruleIndex, .block = block, .agreed = agreed};
            }
        };
        if (everything) {
            for (std::size_t ruleIndex = 0; ruleIndex < kSeedRules; ++ruleIndex) {
                const SeedRule rule = ruleAt(ruleIndex);
                std::vector<std::vector<noise::PerlinNoise>> offsetBlocks;
                std::vector<std::vector<noise::PerlinNoise>> temperatureBlocks;
                std::vector<std::vector<noise::PerlinNoise>> vegetationBlocks;
                for (const World& world : full) {
                    offsetBlocks.push_back(
                        blocksFor(rule, seedFor(rule, world.seed, kOffsetId), blocksNeeded));
                    temperatureBlocks.push_back(
                        blocksFor(rule, seedFor(rule, world.seed, kTemperatureId), blocksNeeded));
                    vegetationBlocks.push_back(
                        blocksFor(rule, seedFor(rule, world.seed, kVegetationId), blocksNeeded));
                }
                for (std::size_t block = 0; block < kBlockOffsets; ++block) {
                    std::size_t agreed = 0;
                    for (std::size_t w = 0; w < full.size(); ++w) {
                        agreed +=
                            scoreCandidate(noises, nether, biomes, full[w], offsetBlocks[w],
                                           temperatureBlocks[w], vegetationBlocks[w], block, shift)
                                .agree;
                    }
                    record(ruleIndex, block, agreed);
                }
                if ((ruleIndex % 25) == 24) {
                    std::printf("  ... %zu/%zu rules\n", ruleIndex + 1, kSeedRules);
                    std::fflush(stdout);
                }
            }
        } else {
            for (std::size_t i = 0; i < draws; ++i) {
                const auto ruleIndex =
                    static_cast<std::size_t>(draw.nextInt(static_cast<std::int32_t>(kSeedRules)));
                const auto block = static_cast<std::size_t>(
                    draw.nextInt(static_cast<std::int32_t>(kBlockOffsets)));
                const SeedRule rule = ruleAt(ruleIndex);
                std::size_t agreed = 0;
                for (const World& world : full) {
                    agreed +=
                        scoreCandidate(
                            noises, nether, biomes, world,
                            blocksFor(rule, seedFor(rule, world.seed, kOffsetId), blocksNeeded),
                            blocksFor(rule, seedFor(rule, world.seed, kTemperatureId),
                                      blocksNeeded),
                            blocksFor(rule, seedFor(rule, world.seed, kVegetationId), blocksNeeded),
                            block, shift)
                            .agree;
                }
                record(ruleIndex, block, agreed);
                if ((i % 64) == 63) {
                    std::printf("  ... %zu/%zu draws\n", i + 1, draws);
                    std::fflush(stdout);
                }
            }
        }

        std::size_t total = 0;
        std::size_t sum = 0;
        std::size_t least = fullCells;
        for (std::size_t i = 0; i < histogram.size(); ++i) {
            total += histogram[i];
            sum += histogram[i] * i;
            if (histogram[i] != 0) {
                least = std::min(least, i);
            }
        }
        const double mean =
            total == 0 ? 0.0 : static_cast<double>(sum) / static_cast<double>(total);
        double variance = 0.0;
        for (std::size_t i = 0; i < histogram.size(); ++i) {
            const double delta = static_cast<double>(i) - mean;
            variance += static_cast<double>(histogram[i]) * delta * delta;
        }
        variance = total == 0 ? 0.0 : variance / static_cast<double>(total);
        const double sd = std::sqrt(variance);
        const auto percent = [&](double count) {
            return 100.0 * count / static_cast<double>(fullCells);
        };
        std::printf("null over %zu candidates at %zu cells: mean %.2f (%.2f%%), sd %.2f (%.2f "
                    "pts), min %zu (%.2f%%), max %zu (%.2f%%)\n",
                    total, fullCells, mean, percent(mean), sd, percent(sd), least,
                    percent(static_cast<double>(least)), worst,
                    percent(static_cast<double>(worst)));
        const auto quantile = [&](double fraction) {
            const auto target = static_cast<std::size_t>(fraction * static_cast<double>(total));
            std::size_t seen = 0;
            for (std::size_t i = 0; i < histogram.size(); ++i) {
                seen += histogram[i];
                if (seen >= target) {
                    return i;
                }
            }
            return histogram.size() - 1;
        };
        std::printf("  rank distribution: p50 %zu (%.2f%%), p90 %zu (%.2f%%), p99 %zu (%.2f%%), "
                    "p99.9 %zu (%.2f%%)\n",
                    quantile(0.50), percent(static_cast<double>(quantile(0.50))), quantile(0.90),
                    percent(static_cast<double>(quantile(0.90))), quantile(0.99),
                    percent(static_cast<double>(quantile(0.99))), quantile(0.999),
                    percent(static_cast<double>(quantile(0.999))));
        std::printf("  the largest score was rule %zu block %zu (%s): %zu/%zu (%.2f%%), %.2f sd "
                    "above the mean\n",
                    worstAt.seedRule, worstAt.block, describe(ruleAt(worstAt.seedRule)).c_str(),
                    worst, fullCells, percent(static_cast<double>(worst)),
                    nonZero(sd) ? (static_cast<double>(worst) - mean) / sd : 0.0);
        return 0;
    }

    // --- the scan -----------------------------------------------------------
    std::printf("candidate space: %zu seed rules x %zu block offsets = %zu candidates\n",
                kSeedRules, kBlockOffsets, kSeedRules * kBlockOffsets);
    if (splitMode) {
        std::printf("--split: the shift is HELD AT ZERO, so `offset` is out of the candidate and "
                    "only the temperature and vegetation rules are being asked to be right. This "
                    "is not vanilla's chain; a score here is not a match\n");
    }
    std::printf("stage 1 over %zu cells (%zu worlds, chunk stride %d)\n", coarseCells,
                coarse.size(), kScanStride);

    std::vector<Result> best;
    std::vector<std::size_t> histogram(coarseCells + 1, 0);
    constexpr std::size_t kKeep = 32;
    for (std::size_t ruleIndex = 0; ruleIndex < kSeedRules; ++ruleIndex) {
        const SeedRule rule = ruleAt(ruleIndex);
        std::vector<std::vector<noise::PerlinNoise>> offsetBlocks;
        std::vector<std::vector<noise::PerlinNoise>> temperatureBlocks;
        std::vector<std::vector<noise::PerlinNoise>> vegetationBlocks;
        offsetBlocks.reserve(coarse.size());
        temperatureBlocks.reserve(coarse.size());
        vegetationBlocks.reserve(coarse.size());
        for (const World& world : coarse) {
            offsetBlocks.push_back(
                blocksFor(rule, seedFor(rule, world.seed, kOffsetId), blocksNeeded));
            temperatureBlocks.push_back(
                blocksFor(rule, seedFor(rule, world.seed, kTemperatureId), blocksNeeded));
            vegetationBlocks.push_back(
                blocksFor(rule, seedFor(rule, world.seed, kVegetationId), blocksNeeded));
        }
        for (std::size_t block = 0; block < kBlockOffsets; ++block) {
            std::size_t agreed = 0;
            for (std::size_t w = 0; w < coarse.size(); ++w) {
                agreed += scoreCandidate(noises, nether, biomes, coarse[w], offsetBlocks[w],
                                         temperatureBlocks[w], vegetationBlocks[w], block, shift)
                              .agree;
            }
            ++histogram[agreed];
            if (best.size() < kKeep || agreed > best.back().agreed) {
                best.push_back({ruleIndex, block, agreed});
                std::sort(best.begin(), best.end(),
                          [](const Result& a, const Result& b) { return a.agreed > b.agreed; });
                if (best.size() > kKeep) {
                    best.resize(kKeep);
                }
            }
        }
        if ((ruleIndex % 100) == 99) {
            std::printf("  ... %zu/%zu rules\n", ruleIndex + 1, kSeedRules);
            std::fflush(stdout);
        }
    }

    std::size_t total = 0;
    std::size_t sum = 0;
    std::size_t worst = 0;
    for (std::size_t i = 0; i < histogram.size(); ++i) {
        total += histogram[i];
        sum += histogram[i] * i;
        if (histogram[i] != 0) {
            worst = i;
        }
    }
    const double mean = total == 0 ? 0.0 : static_cast<double>(sum) / static_cast<double>(total);
    double variance = 0.0;
    for (std::size_t i = 0; i < histogram.size(); ++i) {
        const double delta = static_cast<double>(i) - mean;
        variance += static_cast<double>(histogram[i]) * delta * delta;
    }
    variance = total == 0 ? 0.0 : variance / static_cast<double>(total);

    // THE NULL IS MEASURED, NOT ASSUMED: every candidate in the space is
    // wrong, so their agreement counts ARE the null distribution.
    std::printf("null over %zu scored candidates: mean %.2f/%zu (%.2f%%), sd %.2f, max %zu/%zu "
                "(%.2f%%)\n",
                total, mean, coarseCells, 100.0 * mean / static_cast<double>(coarseCells),
                std::sqrt(variance), worst, coarseCells,
                100.0 * static_cast<double>(worst) / static_cast<double>(coarseCells));

    // The rank distribution, not just its two ends: a maximum quoted without
    // the shape underneath it is how a score at the null reads as an outlier.
    const auto quantile = [&](double fraction) {
        const auto target = static_cast<std::size_t>(fraction * static_cast<double>(total));
        std::size_t seen = 0;
        for (std::size_t i = 0; i < histogram.size(); ++i) {
            seen += histogram[i];
            if (seen >= target) {
                return i;
            }
        }
        return histogram.size() - 1;
    };
    std::printf("  rank distribution: p50 %zu (%.2f%%), p90 %zu (%.2f%%), p99 %zu (%.2f%%), "
                "p99.9 %zu (%.2f%%)\n",
                quantile(0.50),
                100.0 * static_cast<double>(quantile(0.50)) / static_cast<double>(coarseCells),
                quantile(0.90),
                100.0 * static_cast<double>(quantile(0.90)) / static_cast<double>(coarseCells),
                quantile(0.99),
                100.0 * static_cast<double>(quantile(0.99)) / static_cast<double>(coarseCells),
                quantile(0.999),
                100.0 * static_cast<double>(quantile(0.999)) / static_cast<double>(coarseCells));

    // The modern rule through the SAME cells, as a reference point rather than
    // a candidate: it is known wrong for a legacy dimension, so where it lands
    // says what "wrong" looks like on this sample.
    std::size_t modernAgreed = 0;
    for (const World& world : coarse) {
        modernAgreed +=
            scoreCandidate(noises, nether, biomes, world,
                           modernBlocksFor(noises.offset, kOffsetId, world.seed),
                           modernBlocksFor(noises.temperature, kTemperatureId, world.seed),
                           modernBlocksFor(noises.vegetation, kVegetationId, world.seed), 0, shift)
                .agree;
    }
    std::printf("  for reference, the MODERN rule on these same cells: %zu/%zu (%.2f%%)\n",
                modernAgreed, coarseCells,
                100.0 * static_cast<double>(modernAgreed) / static_cast<double>(coarseCells));

    std::printf("stage 1 top %zu:\n", best.size());
    for (std::size_t i = 0; i < best.size(); ++i) {
        std::printf("  #%2zu rule %3zu block %3zu: %zu/%zu (%.2f%%)  %s\n", i + 1, best[i].seedRule,
                    best[i].block, best[i].agreed, coarseCells,
                    100.0 * static_cast<double>(best[i].agreed) / static_cast<double>(coarseCells),
                    describe(ruleAt(best[i].seedRule)).c_str());
    }

    // Stage 2: the survivors over the FULL sample, so nothing is reported at a
    // denominator smaller than the oracle actually offers.
    const std::vector<World> full = loadWorlds(kDistinctSeeds, kNetherChunkStride);
    std::printf("stage 2, full sample:\n");
    std::size_t fullCells = 0;
    for (const World& world : full) {
        fullCells += world.cells.size();
    }
    double bestRate = 0.0;
    for (const Result& result : best) {
        const SeedRule rule = ruleAt(result.seedRule);
        Tally overall{biomes.size()};
        for (const World& world : full) {
            const auto offsetBlocks =
                blocksFor(rule, seedFor(rule, world.seed, kOffsetId), blocksNeeded);
            const auto temperatureBlocks =
                blocksFor(rule, seedFor(rule, world.seed, kTemperatureId), blocksNeeded);
            const auto vegetationBlocks =
                blocksFor(rule, seedFor(rule, world.seed, kVegetationId), blocksNeeded);
            overall.absorb(scoreCandidate(noises, nether, biomes, world, offsetBlocks,
                                          temperatureBlocks, vegetationBlocks, result.block,
                                          shift));
        }
        bestRate = std::max(bestRate, overall.rate());
        std::printf(
            "  rule %3zu block %3zu: %zu/%zu (%.2f%%), baseline %.2f%%, interior "
            "%zu/%zu (%.2f%%)  %s\n",
            result.seedRule, result.block, overall.agree, overall.cells, 100.0 * overall.rate(),
            100.0 * overall.chanceBaseline(), overall.interiorAgree, overall.interiorCells,
            overall.interiorCells == 0 ? 0.0
                                       : 100.0 * static_cast<double>(overall.interiorAgree) /
                                             static_cast<double>(overall.interiorCells),
            describe(rule).c_str());
    }
    std::printf("full sample: %zu cells over %zu worlds; best survivor rate %.2f%%\n", fullCells,
                full.size(), 100.0 * bestRate);
    return 0;
}
