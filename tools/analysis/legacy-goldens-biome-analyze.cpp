// WHAT THIS IS FOR. How a NAMED noise's identifier becomes a Java LCG seed
// under `legacy_random_source` is unsolved (SPEC §11). tools/analysis/
// legacy-seed-analyze.cpp attacks it through synthetic probe dimensions whose
// terrain height is a readback of one noise; this file attacks it through a
// different oracle entirely — the eight golden Nether regions, which are the
// real server's own output from the real legacy seeding of the real noises.
//
// THE ORACLE. `.fixtures/1.21.11/regions/seed-<s>/nether/r.0.0.mca` at seeds
// 0, 1, -1, 42, 2891948927356891, -4172144997902289642, Long.MAX_VALUE and
// Long.MIN_VALUE. Those eight are SIX INDEPENDENT WORLDS, not eight: a legacy
// dimension's randomness is `new java.util.Random(worldSeed)`, whose scramble
// keeps only the low 48 bits of the seed, so 0 collides with Long.MIN_VALUE
// and -1 with Long.MAX_VALUE. Say six worlds. The scan below uses the six
// distinct ones; only the modern-rule sanity check uses all eight, because
// the number it has to reproduce was measured over all eight.
//
// THE READBACK. The Nether's `biome_source` is multi_noise, and its router
// sets continents, erosion, depth and ridges to the constant 0.0 — so of the
// six climate parameters only `temperature` and `vegetation` vary, and the
// biome stored at a 4x4x4 cell is a function of those two alone. Three noises
// feed them:
//
//     shift_x = flat_cache(cache_2d(shift_a(minecraft:offset)))
//     shift_z = flat_cache(cache_2d(shift_b(minecraft:offset)))
//     temperature = shifted_noise(minecraft:temperature,
//                                 shift_x, 0.0, shift_z, xz_scale 0.25,
//                                 y_scale 0.0)
//     vegetation  = the same over minecraft:vegetation
//
// so each stored biome is a COARSE readback of (temperature, vegetation,
// offset) at that column: not a number, a cell of a five-way partition of the
// (T, H) plane. That is far less information per column than the terrain-height
// readback legacy-seed-analyze inverts — but there are ~2 million columns of
// it, it comes from vanilla's own noises rather than from a synthetic probe,
// and it needs no probe world at all.
//
// THE PARAMETER TABLE, and where it comes from. The pack ships
// `worldgen/multi_noise_biome_source_parameter_list/nether.json` as nothing
// but `{"preset": "minecraft:nether"}`; the five parameter points are compiled
// into the jar. This project does NOT read them off minecraft.wiki and does
// NOT read the jar's code: `tools/fetch-vanilla` runs the server's own data
// generator (`--reports`) and keeps what it dumps at
// `.fixtures/<version>/biome_parameters/minecraft/nether.json`. That is
// observed output of the vanilla server, which CLAUDE.md permits where it
// forbids the source. `--preset` below prints the table it loaded, so the
// numbers a run depends on are visible in the run rather than quoted from
// memory. See lib/include/stratum/biome/parameter_list.hpp.
//
// THE CONTROL COMES FIRST, and it is three separate things, because a
// readback is worthless until the thing that decodes it has been shown to
// recover a rule whose seeding is already known and correct.
//
//   --control  THE DECODER. The overworld goldens at the same eight seeds are
//              generated by the MODERN seeding, which this build reproduces
//              exactly. Run the identical decode — stored biome per cell
//              against `biome::ParameterList::find` over the dimension's own
//              climate router — and the modern rule must come back at ~100%,
//              while the same rule at worldSeed + 1 must fall to the null.
//              The positive arm says the decoder can see a correct seeding;
//              the negative arm says it is the SEEDING doing the work and not
//              the decoder accepting anything. Neither arm alone is a control.
//
//   --model    THE FORWARD MODEL. The scan cannot use the library's
//              `NormalNoise`, which only builds from Xoroshiro128++; it needs
//              a hand-rolled stack over Perlin blocks drawn from a candidate
//              generator, and a hand-rolled climate chain over that. Both
//              halves are compared against the library, bit for bit, at the
//              modern seeding where the library is known right:
//
//                stack   this file's sampleNormal over modernBlocksFor
//                        against noise::NormalNoise::sample, for each of the
//                        THREE noises in play — not for some other noise with
//                        a convenient amplitude list
//                chain   this file's shift/shifted_noise/flat_cache chain over
//                        library NormalNoises, against
//                        density::Interpreter evaluating the Nether's own
//                        router entries
//                whole   the composition of the two against the Interpreter
//
//              A wrong valueFactor, a missing second stack, a wrong
//              persistence schedule or a misread of `shift_b`'s axis rotation
//              is caught here rather than shared silently between the scan and
//              its own null.
//
//   --modern   THE NUMBER ALREADY ON RECORD.
//              tests/conformance/vanilla_legacy_nether_climate_gap_test.cpp
//              measured the MODERN derivation at 27.08% biome agreement on the
//              Nether against a 30.23% chance baseline. This file must
//              reproduce both to the cell before anything it says about
//              candidates is worth reading.
//
// ONLY THEN --scan. The candidate space is legacy-seed-analyze.cpp's, read out
// of that file and re-implemented here rather than shared, because that file
// belongs to a different piece of work and nothing in this one may edit it:
//
//   base       (5)  worldSeed; JavaRandom(worldSeed).nextLong(); the low half
//                   of Xoroshiro128PlusPlus(worldSeed).nextLong(); the LCG's
//                   own scramble of the world seed; zero
//   salt      (10)  MD5("ns:path") as first-eight big-endian, first-eight
//                   little-endian, last-eight big-endian, last-eight
//                   little-endian, lo^hi, lo+hi; MD5("path") first-eight
//                   big-endian; String.hashCode("ns:path");
//                   String.hashCode("path"); no salt
//   combine    (3)  base ^ salt, base + salt, base - salt
//   forks      (3)  0, 1 or 2 further rounds of seed = JavaRandom(seed).nextLong()
//   generator  (2)  the Java LCG, or Xoroshiro128++
//   block    (300)  complete Perlin blocks drawn and discarded first
//
// 5 x 10 x 3 x 3 x 2 = 900 seed rules x 300 block offsets = 270,000
// candidates. The rule index is the SAME index legacy-seed-analyze prints, so
// `--candidate 182 0` names deepslate's own derivation in both tools; the
// agreement between the two enumerations is asserted by
// tests/conformance/vanilla_legacy_goldens_biome_test.cpp rather than left to
// the two headers agreeing in prose.
//
// WHAT THE SCAN DOES NOT COVER, stated here and not left to be assumed. It
// inherits every gap of the space it borrows: ONE stack rule (sequential
// Perlin blocks out of one generator), NO frequency variation, NO per-octave
// salting, and no LCG-STEP skip of the kind `minecraft:end_islands` turned out
// to use. And it adds one of its own: the three noises are seeded by ONE rule
// at ONE block offset. A derivation that seeded `offset` differently from
// `temperature`, or that drew all three from a single shared generator in
// declaration order, is outside this space even though every individual noise's
// rule might be inside it. `--split` measures how much that matters by scoring
// temperature and vegetation with `offset` held at its correct-by-assumption
// zero shift; it does not close the gap.
//
// AND THE READBACK'S OWN POWER IS BOUNDED, which is the honest part. A column
// carries at most log2(5) = 2.32 bits and in practice far less, because the
// five cells are wildly unequal in area. Two DIFFERENT climate fields agree on
// a biome about 30% of the time by construction — that is the chance baseline
// `--modern` prints — so the scan cannot distinguish "nearly right" from
// "unrelated", only "exactly right" (100%) from everything else. It is a sieve
// for a correct rule, not a gradient towards one.
//
//   cmake --build --preset release --target stratum_legacy_goldens_biome_analyze
//   A=build/release/tools/analysis/stratum_legacy_goldens_biome_analyze
//   $A .fixtures --preset
//   $A .fixtures --control
//   $A .fixtures --model
//   $A .fixtures --modern
//   $A .fixtures --boundary
//   $A .fixtures --candidate 182 0
//   $A .fixtures --scan            # ~hours in Debug; use the release preset
//
// The fixtures are Mojang-derived and never committed (SPEC §12). Without them
// every mode exits 77, CTest's skip code.
